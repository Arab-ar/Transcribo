"""Конвертер IPA (Международный фонетический алфавит) в русскую кириллицу."""

import re

# Словарь базовых замен (английские звуки -> русские буквы)
# Порядок важен: сначала заменяем длинные сочетания (дифтонги), потом одиночные символы.
IPA_TO_RU = {
    # Дифтонги и сложные гласные
    "eɪ": "эй", "aɪ": "ай", "ɔɪ": "ой", "aʊ": "ау", "əʊ": "оу", "oʊ": "оу",
    "ɪə": "иэ", "eə": "эа", "ʊə": "уа", "juː": "ью", "ju": "ю",
    
    # Долгие гласные
    "iː": "и", "ɑː": "а", "ɔː": "о", "uː": "у", "ɜː": "ё", 
    
    # Краткие гласные
    "ɪ": "и", "e": "э", "æ": "э", "ʌ": "а", "ɒ": "о", "ʊ": "у", "ə": "э",
    
    # Согласные
    "tʃ": "ч", "dʒ": "дж", "ʃ": "ш", "ʒ": "ж", "θ": "с", "ð": "з", "ŋ": "нг",
    "p": "п", "b": "б", "t": "т", "d": "д", "k": "к", "g": "г", "f": "ф", "v": "в",
    "s": "с", "z": "з", "h": "х", "m": "м", "n": "н", "l": "л", "r": "р", "j": "й", "w": "в",
    
    # Знаки ударения и долготы (просто удаляем)
    "ˈ": "", "ˌ": "", "ː": "",
}

def ipa_to_cyrillic(ipa_text: str) -> str:
    """Преобразует строку IPA в русскую транскрипцию."""
    if not ipa_text:
        return ""
    
    result = ipa_text
    
    # Проходим по словарю и делаем замены
    for ipa_sound, ru_sound in IPA_TO_RU.items():
        result = result.replace(ipa_sound, ru_sound)
    
    # Убираем оставшиеся непонятные символы (скобки, точки и т.д.)
    result = re.sub(r'[^а-яА-ЯёЁ\s\-]', '', result)
    
    # Убираем двойные пробелы, если появились
    result = re.sub(r'\s+', ' ', result).strip()
    
    return result